import test from 'node:test';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {readFileSync,existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {join,dirname} from 'node:path';
const root=join(dirname(fileURLToPath(import.meta.url)),'..');

test('static production candidate renders real intake UI with an explicit receipt guard',()=>{
  execFileSync(process.execPath,['scripts/build-static.mjs'],{cwd:root,timeout:12000,stdio:'pipe'});
  const home=readFileSync(join(root,'dist/index.html'),'utf8');
  const client=readFileSync(join(root,'dist/assets/rivet-seller.js'),'utf8');
  assert.match(home,/Your home deserves/);
  assert.match(home,/id="rivet-seller-inquiry"/);
  assert.match(home,/consentToReply/);
  assert.match(home,/mailto:info@rivetauctions\.com/);
  assert.match(client,/rivet-public-intake/);
  assert.match(client,/result.status !== 'received'/);
  assert.match(client,/receipt_not_verified/);
  assert.match(client,/confirmSaved\(result\.reference\)/);
  assert.match(client,/dialog\.showModal\(\)/);
  assert.match(client,/completed = true/);
  assert.match(client,/button\.disabled = completed/);
  assert.doesNotMatch(client,/form\.reset\(\)/);
  const css=readFileSync(join(root,'dist/assets/rivet-seller.css'),'utf8');
  assert.match(css,/\.ra-success-dialog::backdrop/);
  assert.match(css,/\.ra-success-message/);
  assert.doesNotMatch(home,/<!-- INQUIRY_WIDGET -->/);
  const demo=readFileSync(join(root,'dist/demo/index.html'),'utf8');
  assert.match(demo,/id="rivet-demo-inquiry"/);
  assert.match(demo,/DEMO ONLY/);
  assert.match(demo,/No inquiry has been sent or saved/);
  assert.doesNotMatch(demo,/<form[^>]*id="rivet-seller-inquiry"/);
  const buyer=readFileSync(join(root,'dist/buyers/index.html'),'utf8');
  assert.match(buyer,/FOR BUYERS/);
  assert.ok(existsSync(join(root,'dist/privacy/index.html')));
  assert.ok(existsSync(join(root,'dist/terms/index.html')));
  assert.ok(existsSync(join(root,'dist/favicon.svg')));
  assert.match(readFileSync(join(root,'dist/robots.txt'),'utf8'),/Disallow:/);
});